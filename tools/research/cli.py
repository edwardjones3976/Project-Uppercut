"""The research pipeline's front door.

    python -m tools.research.cli harvest <lane> [--limit N]
    python -m tools.research.cli ingest <record-id> --via <fetcher> \
        --url <url> --text-file <path>
    python -m tools.research.cli validate
    python -m tools.research.cli index
    python -m tools.research.cli summary
"""
import io
import json
import os
import sys

from . import gate


def _schema_errors(rec: dict) -> list:
    """Schema check without a hard dependency on jsonschema being installed.

    Falls back to a required-keys check so `validate` still says something
    useful on a machine that has not installed the library.
    """
    path = os.path.join(gate.REPO, "schemas", "research_record.schema.json")
    with io.open(path, encoding="utf-8") as fh:
        schema = json.load(fh)
    body = {k: v for k, v in rec.items() if not k.startswith("_")}
    try:
        import jsonschema
    except ImportError:
        missing = [k for k in schema["required"] if k not in body]
        return ["missing required field %s" % k for k in missing]
    v = jsonschema.Draft7Validator(schema)
    return [e.message for e in v.iter_errors(body)]


def validate() -> int:
    recs = gate.load_all()
    errs = []
    for rec in recs:
        for msg in _schema_errors(rec):
            errs.append("%s: schema: %s" % (rec.get("_file"), msg))
    errs.extend(gate.check_all())
    if errs:
        print("RESEARCH GATE: %d problem(s) in %d record(s)" % (len(errs), len(recs)))
        for e in errs:
            print("  " + e)
        return 1
    print("RESEARCH GATE: OK - %d record(s), no problems" % len(recs))
    return 0


def index() -> int:
    """Write the citation index a human reads, one line per source per lane."""
    recs = gate.load_all()
    out = [
        "<!-- GENERATED by tools/research/cli.py - do not hand-edit. Regenerate:",
        "     python -m tools.research.cli index -->",
        "",
        "# Research citation index",
        "",
        "Every source the project has collected, by lane, with the status this",
        "project has given it. `discovered` means found and nothing more: nobody",
        "has read the method and nothing may be built on it. Only `accepted` may",
        "inform canon, and only a decision record can grant that.",
        "",
    ]
    for lane in gate.LANES:
        here = [r for r in recs if lane in (r.get("research_lane") or [])]
        out.append("## %s (%d)" % (lane.replace("_", " "), len(here)))
        out.append("")
        if not here:
            out.append("_No sources collected yet._")
            out.append("")
            continue
        out.append("| Year | Source | Venue | Tier | Status |")
        out.append("|---|---|---|---|---|")
        for r in sorted(here, key=lambda r: (-(r.get("year") or 0),
                                             r.get("title", ""))):
            link = r.get("doi")
            title = r.get("title", "").replace("|", "/")
            cell = ("[%s](https://doi.org/%s)" % (title, link)) if link else title
            out.append("| %s | %s | %s | %s | %s |"
                       % (r.get("year", "?"), cell,
                          (r.get("journal_or_venue") or "-").replace("|", "/"),
                          r.get("tier", "?"), r.get("canon_status", "?")))
        out.append("")
    path = os.path.join(gate.REPO, "research", "citations", "INDEX.md")
    if not os.path.isdir(os.path.dirname(path)):
        os.makedirs(os.path.dirname(path))
    with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print("wrote research/citations/INDEX.md (%d records)" % len(recs))
    return 0


def main(argv) -> int:
    if not argv:
        print(__doc__)
        return 1
    cmd = argv[0]
    if cmd == "harvest":
        from . import harvest as h
        if len(argv) < 2:
            print("lanes: " + ", ".join(sorted(h.QUERIES)))
            return 1
        limit = 12
        if "--limit" in argv:
            limit = int(argv[argv.index("--limit") + 1])
        res = h.harvest(argv[1], limit)
        print("harvested %(lane)s: %(written)d new record(s), %(skipped)d skipped"
              % res)
        return 0
    if cmd == "ingest":
        from . import ingest as ing
        import io as _io
        if len(argv) < 2:
            print("usage: ingest <record-id> --via <fetcher> --url <url> "
                  "--text-file <path>")
            return 1
        def opt(name, default=None):
            return argv[argv.index(name) + 1] if name in argv else default
        text_file = opt("--text-file")
        if not text_file:
            print("--text-file is required; provenance without content is a note")
            return 1
        with _io.open(text_file, encoding="utf-8") as fh:
            text = fh.read()
        res = ing.ingest(argv[1], opt("--url", ""), text,
                         opt("--via", "manual"))
        print("ingested %(chars)d chars for %(record)s via %(via)s -> %(raw)s"
              % res)
        return 0
    if cmd == "validate":
        return validate()
    if cmd == "index":
        return index()
    if cmd == "summary":
        print(json.dumps(gate.summary(), indent=2))
        return 0
    print(__doc__)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
