"""Generate `docs/decisions/INDEX.md` from the decision files themselves.

WHY THIS EXISTS. An external audit found the README indexing decisions through
0012 while `main` carried 0032 - twenty decisions invisible from the front
door. The index was hand-maintained, so it drifted the moment anyone forgot,
and nothing failed when it did.

This project already has the answer to that class of problem, written in its
own CI: "A generated file allowed to be stale is hand-maintained drift with
extra machinery." So the index is generated from the files, `--check` fails
when it is stale, and the README points at the generated file instead of
carrying a copy that can rot.

It also enforces two things the numbering exists for, because an index is the
natural place to notice them: decision numbers must be CONTIGUOUS from 0001,
and no number may appear twice. Two collisions on 2026-08-09 (a duplicate 0032
and a duplicate 0034) were both found by hand; the next one fails a gate.
"""
import io
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DECISIONS = os.path.join(REPO, "docs", "decisions")
INDEX = os.path.join(DECISIONS, "INDEX.md")

START = ("<!-- [ Claude (Cowork) | Claude Opus 5 (claude-opus-5) | "
         "2026-08-09 20:55 UTC | decision index start ] -->")
END = ("<!-- [ Claude (Cowork) | Claude Opus 5 (claude-opus-5) | "
       "2026-08-09 20:55 UTC | decision index end ] -->")

NUMBERED = re.compile(r"^(\d{4})-(.+)\.md$")
HEADING = re.compile(r"^#\s+Decision\s+(\d{4})\s*[-—:]*\s*(.*)$")


def collect():
    """Every numbered decision, as (number, filename, title). Fails closed."""
    found = {}
    problems = []
    for fn in sorted(os.listdir(DECISIONS)):
        m = NUMBERED.match(fn)
        if not m:
            continue
        num = m.group(1)
        path = os.path.join(DECISIONS, fn)
        title = ""
        with io.open(path, encoding="utf-8") as fh:
            for line in fh:
                h = HEADING.match(line.strip())
                if h:
                    if h.group(1) != num:
                        problems.append(
                            "%s declares itself Decision %s - the filename and "
                            "the heading disagree, and one of them is wrong"
                            % (fn, h.group(1)))
                    title = h.group(2).strip()
                    break
        if not title:
            problems.append("%s has no '# Decision NNNN - title' heading" % fn)
        if num in found:
            problems.append(
                "Decision %s is claimed by TWO files: %s and %s. A decision "
                "number is an identity, not a label - resolve which one it is "
                "and renumber the other." % (num, found[num][0], fn))
        found[num] = (fn, title)

    nums = sorted(found)
    if nums:
        expected = ["%04d" % i for i in range(1, int(nums[-1]) + 1)]
        missing = [n for n in expected if n not in found]
        if missing:
            problems.append(
                "decision numbers are not contiguous - missing %s. A gap means "
                "a decision was lost or never written, and either way the "
                "record does not say what happened." % ", ".join(missing))
    return [(n,) + found[n] for n in nums], problems


def render(rows):
    out = [START,
           "# Decision index",
           "",
           "**Generated by `tools/gen_decision_index.py`. Do not hand-edit -",
           "run the tool.** `--check` fails CI when this file is stale, and the",
           "generator also refuses a duplicate or non-contiguous number.",
           "",
           "| # | Decision |",
           "|---|---|"]
    for num, fn, title in rows:
        out.append("| %s | [%s](%s) |" % (num, title.replace("|", "\\|"), fn))
    out += ["", "%d decisions, 0001-%s, contiguous."
            % (len(rows), rows[-1][0] if rows else "none"), "", END, ""]
    return "\n".join(out)


def main(argv):
    rows, problems = collect()
    if problems:
        for p in problems:
            sys.stderr.write("REFUSED: %s\n" % p)
        return 2
    want = render(rows)
    if "--check" in argv:
        have = ""
        if os.path.exists(INDEX):
            with io.open(INDEX, encoding="utf-8") as fh:
                have = fh.read()
        if have != want:
            sys.stderr.write(
                "docs/decisions/INDEX.md is stale. Run "
                "`python -m tools.gen_decision_index`.\n")
            return 1
        sys.stdout.write("decision index is current: %d decisions\n" % len(rows))
        return 0
    with io.open(INDEX, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(want)
    sys.stdout.write("wrote %s (%d decisions)\n" % (INDEX, len(rows)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
