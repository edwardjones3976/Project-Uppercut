"""Stable documents may not carry volatile evidence tallies.

An external review of 2026-08-03 caught the README at 402 tests and nine of eleven
checks while reality stood at 463 and eleven of eleven - and contradicting itself about
whether steps 11-12 were done - and the ROADMAP opening with "Phase 0: in progress" a
day after the gate was recorded PASSED. Hand-maintained copies of moving values are the
documentation form of the declared-but-inert defect: correct when written, false when
read, and nothing responsible for noticing.

The rule this file enforces: volatile numbers live in the GENERATED STATUS.md only.
A stable document that wants to cite the test count points at STATUS.md instead.
"""
from __future__ import annotations
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

STABLE_DOCS = ("README.md", "ROADMAP.md", "PROJECT_NOTES.md", "PROJECT_PLAN.md")

VOLATILE = [
    # "402 tests", "463 tests in CI", "the 463-test suite"
    (re.compile(r"\b\d{2,4}[- ]tests?\b|\b\d{2,4} tests\b", re.I),
     "a hard-coded test count (belongs in STATUS.md)"),
    # "nine of the eleven", "eleven of eleven", "9/11 checks", "10 of 11 checks"
    (re.compile(r"\b(?:one|two|three|four|five|six|seven|eight|nine|ten|eleven|\d+)\s+"
                r"of\s+(?:the\s+)?(?:eleven|\d+)\s+(?:required\s+)?checks\b", re.I),
     "a hard-coded gate-check tally (belongs in STATUS.md)"),
    (re.compile(r"\b\d+/\d+ checks\b", re.I),
     "a hard-coded gate-check tally (belongs in STATUS.md)"),
]


def _violations(text: str) -> list:
    out = []
    for pattern, why in VOLATILE:
        for m in pattern.finditer(text):
            out.append(f"{m.group(0)!r}: {why}")
    return out


def test_stable_documents_carry_no_volatile_tallies():
    for name in STABLE_DOCS:
        text = (REPO / name).read_text(encoding="utf-8")
        assert _violations(text) == [], f"{name} restates volatile evidence: " \
                                        f"{_violations(text)}"


def test_the_roadmap_does_not_contradict_the_phase0_gate():
    """phase0_status.md records the gate PASSED on 2026-08-02; the ROADMAP's current-
    state header may not go on saying 'in progress' about a phase with a closed gate."""
    roadmap = (REPO / "ROADMAP.md").read_text(encoding="utf-8")
    head = roadmap[:600]
    assert not re.search(r"Phase 0[^\n]*in progress", head), \
        "ROADMAP still says Phase 0 is in progress; its gate is recorded PASSED"


def test_the_readme_does_not_contradict_itself_about_step_completion():
    """The specific self-contradiction the review caught: 'all twelve steps defined'
    in one paragraph, 'remaining: steps 11-12' in another."""
    readme = (REPO / "README.md").read_text(encoding="utf-8")
    claims_all_defined = re.search(r"all twelve", readme, re.I)
    claims_remaining = re.search(r"[Rr]emaining[^\n]*steps? 11", readme)
    assert not (claims_all_defined and claims_remaining), \
        "README claims all twelve steps defined AND steps 11-12 remaining"


def test_status_md_is_generated_and_says_so():
    status = (REPO / "STATUS.md").read_text(encoding="utf-8")
    assert "GENERATED by tools/gen_status.py" in status
    assert "do not hand-edit" in status


# ---- the guard proven non-vacuous, per house rule ---------------------------

def test_the_guard_fires_on_a_test_count():
    assert _violations("the suite now stands at 463 tests in CI")
    assert _violations("a 402-test suite")


def test_the_guard_fires_on_a_check_tally():
    assert _violations("nine of the eleven required checks green")
    assert _violations("eleven of eleven checks")
    assert _violations("9/11 checks green")


def test_the_guard_permits_stable_prose():
    assert _violations("the eleven required automated checks are enforced in CI") == []
    assert _violations("mutation-proven tests cover every validator") == []
    assert _violations("see STATUS.md for current evidence") == []
