"""STATUS.md must not drift out of date without saying so.

An external gap review on 2026-08-05 found `STATUS.md` reporting 568 tests at
commit 566fff9 while the remote head was hundreds of commits of work later, with
710 tests. Its engine-phase line was still correct - Phase N really is the latest
proven C++ phase - but its operational picture was a day stale, and a generated
status file that is quietly stale is worse than none: it is cited as evidence.

WHY THIS GUARD CHECKS THE TEST COUNT AND NOT THE COMMIT HASH. The obvious check -
"the recorded commit must equal HEAD" - cannot work. Regenerating STATUS.md
changes STATUS.md, which changes the next commit, so the file can never record
the commit that contains it. The test count has no such circularity: it is a
property of the tree, it is the number a reader actually leans on, and it is
exactly the field that was wrong.

The count is obtained by asking pytest to collect, in a subprocess, so this guard
measures the same thing a reader would get by running the suite rather than a
hand-maintained tally.
"""
import os
import re
import subprocess
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATUS = os.path.join(ROOT, "STATUS.md")


def _status_text():
    with open(STATUS, "r", encoding="utf-8") as fh:
        return fh.read()


def _collected_count():
    """How many tests this tree actually has, per pytest itself."""
    out = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q",
         "-p", "no:cacheprovider"],
        cwd=ROOT, capture_output=True, text=True)
    m = re.search(r"(\d+)\s+tests? collected", out.stdout)
    if not m:
        m = re.search(r"^(\d+) tests? collected", out.stdout, re.M)
    if not m:
        pytest.skip("could not read a collection count from pytest output")
    return int(m.group(1))


def test_status_file_exists_and_is_generated():
    assert os.path.exists(STATUS), "STATUS.md is missing"
    assert "GENERATED by tools/gen_status.py" in _status_text(), \
        "STATUS.md has lost its generated-file banner and may have been hand-edited"


# How far out of date the count may drift before it is misleading. This is a
# STALENESS detector, not an equality check, and the difference is forced rather
# than chosen: `gen_status` regenerates STATUS.md by RUNNING THE SUITE, and this
# test is in that suite. An exact check therefore fails during the very run that
# would fix it, and the generator then writes "(FAILURES)" into the file it is
# repairing - which is exactly what happened the first time this guard was
# written. A small tolerance breaks that self-reference; 5% still catches the
# defect this exists for (568 stated against 714 real is 20% out).
DRIFT_TOLERANCE = 0.05


def test_status_reports_a_believable_test_count():
    """The field that was wrong on 2026-08-05, and the one a reader leans on."""
    text = _status_text()
    m = re.search(r"Test suite \|\s*\*\*(\d+) passed\*\*", text)
    assert m, "STATUS.md no longer states a test count in the expected form"
    stated = int(m.group(1))
    actual = _collected_count()
    drift = abs(stated - actual) / float(actual)
    assert drift <= DRIFT_TOLERANCE, (
        "STATUS.md says %d tests; the tree collects %d - %.1f%% out, past the "
        "%.0f%% staleness tolerance. Regenerate it:\n"
        "    python -m tools.gen_status"
        % (stated, actual, 100.0 * drift, 100.0 * DRIFT_TOLERANCE))


# A THIRD CHECK WAS TRIED HERE AND REMOVED, and the reason is worth keeping.
#
# `gen_status` writes "(FAILURES)" into STATUS.md when the suite it ran was red,
# so a guard asserting that marker is absent looks obviously right. It is a trap.
# The guard lives in the suite that `gen_status` runs, so once STATUS.md is dirty
# the suite can never be green, so the file can never be regenerated clean: the
# marker becomes permanent and the only exit is hand-editing a generated file.
# Observed directly on 2026-08-05 - two generations in a row wrote "(FAILURES)"
# because the previous generation had.
#
# The rule it teaches: a guard that reads an artifact produced by the run it is
# part of must never be able to make that artifact unrepairable. The drift check
# above survives because its tolerance leaves the repair path open.


def test_status_does_not_overclaim_an_engine_phase():
    """The distinction an external review flagged: a `feat(core)` commit subject
    is not proof of a C++ engine phase. STATUS.md is the authority on which
    phase is proven, so it must name exactly one and must not silently promote
    a phase that only has a contract."""
    text = _status_text()
    m = re.search(r"Latest engine phase proven \| Phase ([A-Z])", text)
    assert m, "STATUS.md no longer names a latest proven engine phase"
    phase = m.group(1)
    # Phases with a contract but no C++ must NOT appear in that field. Update
    # this set when a phase is genuinely ported and proven byte-identical.
    contract_only = {"P", "Q", "R", "S"}
    assert phase not in contract_only, (
        "STATUS.md claims Phase %s is the latest proven engine phase, but that "
        "phase is contract-only: no C++ artifact has been proven byte-identical "
        "to its analyzer. If it has now been ported, remove it from "
        "`contract_only` in this test as part of the same change." % phase)


def test_the_generator_is_reachable():
    """A guard that tells you to regenerate must be able to point at something
    that exists."""
    assert os.path.exists(os.path.join(ROOT, "tools", "gen_status.py"))
